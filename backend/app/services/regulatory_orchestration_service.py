@dataclass
class RegulatoryContext:
    """Resolved context for a regulatory AI request."""

    user_id: uuid.UUID
    user_role: str
    institution_id: uuid.UUID | None
    institution_name: str | None
    # Effective frameworks are the frameworks visible to this user/institution
    effective_framework_ids: list[uuid.UUID] = field(default_factory=list)
    effective_framework_codes: list[str] = field(default_factory=list)
    # Scope hints resolved from the intent
    module_id: uuid.UUID | None = None
    programme_id: uuid.UUID | None = None
    target_framework_code: str | None = None
    # Resolved intents for multi-step planning
    primary_intent: str = "qa_general"
    secondary_intents: list[str] = field(default_factory=list)


async def resolve_regulatory_context(
    db: AsyncSession,
    user: User,
    *,
    primary_intent: str,
    secondary_intents: list[str] | None = None,
    module_id: uuid.UUID | None = None,
    programme_id: uuid.UUID | None = None,
    target_framework_code: str | None = None,
) -> RegulatoryContext:
    """Build a RegulatoryContext by resolving effective frameworks for the user's institution."""
    institution_id: uuid.UUID | None = getattr(user, "institution_id", None)
    institution_name: str | None = None

    if institution_id is not None:
        # Resolve institution name
        from app.models.institution import Institution
        result = await db.execute(
            select(Institution).where(Institution.id == institution_id)
        )
        inst = result.scalar_one_or_none()
        if inst:
            institution_name = inst.name

    effective_framework_ids, effective_framework_codes = await _resolve_effective_frameworks(
        db, institution_id=institution_id, today=date.today()
    )

    return RegulatoryContext(
        user_id=user.id,
        user_role=user.role if isinstance(user.role, str) else user.role.value,
        institution_id=institution_id,
        institution_name=institution_name,
        effective_framework_ids=effective_framework_ids,
        effective_framework_codes=effective_framework_codes,
        module_id=module_id,
        programme_id=programme_id,
        target_framework_code=target_framework_code,
        primary_intent=primary_intent,
        secondary_intents=secondary_intents or [],
    )


# ---------------------------------------------------------------------------
# Framework resolver
# ---------------------------------------------------------------------------


async def _resolve_effective_frameworks(
    db: AsyncSession,
    *,
    institution_id: uuid.UUID | None,
    today: date,
) -> tuple[list[uuid.UUID], list[str]]:
    """Return (ids, codes) for all active framework versions visible to this institution.

    Global frameworks (institution_id = NULL) are always included.
    Institution-specific frameworks are included only when institution_id matches.
    Tenant isolation is enforced here — callers MUST NOT bypass this.
    """
    stmt = (
        select(QualityFramework)
        .where(QualityFramework.is_active.is_(True))
        .options(selectinload(QualityFramework.versions))
    )

    if institution_id is not None:
        stmt = stmt.where(
            or_(
                QualityFramework.institution_id.is_(None),
                QualityFramework.institution_id == institution_id,
            )
        )
    else:
        # No institution context — global frameworks only
        stmt = stmt.where(QualityFramework.institution_id.is_(None))

    result = await db.execute(stmt)
    frameworks = result.scalars().all()

    ids: list[uuid.UUID] = []
    codes: list[str] = []
    for fw in frameworks:
        has_active_version = any(
            v.status == "active"
            and (v.effective_from is None or v.effective_from <= today)
            and (v.effective_to is None or v.effective_to >= today)
            for v in (fw.versions or [])
        )
        if has_active_version:
            ids.append(fw.id)
            codes.append(fw.code)

    return ids, codes


async def resolve_active_version_for_framework(
    db: AsyncSession,
    framework_code: str,
    institution_id: uuid.UUID | None = None,
) -> FrameworkVersion | None:
    """Return the currently active FrameworkVersion for a given framework code.

    Enforces tenant isolation — returns None if the framework is not visible to the institution.
    """
    today = date.today()
    stmt = (
        select(FrameworkVersion)
        .join(QualityFramework, FrameworkVersion.framework_id == QualityFramework.id)
        .where(QualityFramework.code == framework_code)
        .where(QualityFramework.is_active.is_(True))
        .where(FrameworkVersion.status == "active")
        .options(
            selectinload(FrameworkVersion.standards),
        )
    )

    if institution_id is not None:
        stmt = stmt.where(
            or_(
                QualityFramework.institution_id.is_(None),
                QualityFramework.institution_id == institution_id,
            )
        )
    else:
        stmt = stmt.where(QualityFramework.institution_id.is_(None))

    result = await db.execute(stmt)
    return result.scalar_one_or_none()


