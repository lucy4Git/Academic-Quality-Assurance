"""Regulatory Orchestration Service — Phase C, C10.

Provides:
- RegulatoryContext: resolved user, role, tenant, institution hierarchy, and effective frameworks
- FrameworkResolver: automatic framework resolution via applicability engine
- RegulatoryExecutionPlanner: internal execution planning (never exposed to callers)
- RegulatoryResponse: structured response with citation requirements and honest generation mode

Security:
- Tenant isolation enforced: only frameworks with institution_id = NULL (global) or matching
  the user's institution are returned.
- Chain-of-thought / execution plan is NEVER returned to callers.
- Citation is REQUIRED for every regulatory answer sourced from framework content.
- EQUIVALENT cross-framework mappings require human_verified = True before deduplication.
- No eval() / exec() anywhere in rule evaluation.

Generation modes:
- LLM: answer generated by language model with retrieved regulatory context
- DETERMINISTIC_TEMPLATE: answer built from structured DB data with no LLM generation
- HYBRID: structured data + LLM narrative synthesis
- MANUAL_REVIEW_REQUIRED: system cannot provide a reliable answer; escalation recommended
"""

